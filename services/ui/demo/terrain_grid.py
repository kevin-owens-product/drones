"""Pack the demo range's heightmap into a module the physics can read offline.

Reads demo/assets/terrain-height.png (made by demo/terrain.py from AWS Terrain
Tiles) and writes demo/terrain-grid.mjs: an 80 m grid of ground heights as
base64 bytes, so the radio model can sample terrain in Node and the browser
without decoding an image.

    python3 demo/terrain_grid.py   (needs numpy and Pillow)
"""
from __future__ import annotations

import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).parent
meta = json.loads((HERE / "assets" / "terrain.json").read_text())
e0, e1 = meta["elevation_m"]
img = Image.open(HERE / "assets" / "terrain-height.png").convert("L")
COLS, ROWS = img.width // 2, img.height // 2
small = np.asarray(img.resize((COLS, ROWS), Image.Resampling.BOX), dtype=np.uint8)
b64 = base64.b64encode(small.tobytes()).decode()
(HERE / "terrain-grid.mjs").write_text(
    "// Generated by demo/terrain_grid.py from assets/terrain-height.png. Do not edit.\n"
    "// Ground height on the demo range: AWS Terrain Tiles (SRTM, USGS NED), 80 m cells,\n"
    "// rows north to south, 8-bit between the lowest and highest elevation.\n"
    f"export const GRID = {{ cols: {COLS}, rows: {ROWS}, x0: -7000, x1: 7000, y0: -5000, y1: 5000, e0: {e0}, e1: {e1} }};\n"
    f'export const DATA = "{b64}";\n'
)
print(COLS, ROWS, len(b64))
